<?php

require_once dirname(__DIR__) . '/includes/auth.php';
require_once dirname(__DIR__) . '/includes/csrf.php';
require_once dirname(__DIR__) . '/includes/functions.php';
require_once dirname(__DIR__) . '/includes/lti-account-link.php';

requireTeacher();

$userId = currentUserId();
$hasLtiIdentity = ltiAccountLinkHasIdentity($pdo, $userId);
$error = '';
$notice = '';
$generatedCode = '';
if (!empty($_GET['code'])) {
    $generatedCode = (string) ($_SESSION['lti_account_link_code'] ?? '');
    unset($_SESSION['lti_account_link_code']);
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    verifyCsrf();
    $action = (string) ($_POST['action'] ?? '');
    try {
        if ($action === 'generate') {
            $_SESSION['lti_account_link_code'] = ltiCreateTeacherAccountLinkCode($pdo, $userId);
            redirect('lti-account-link.php?code=1');
        } elseif ($action === 'redeem') {
            if (!$hasLtiIdentity) {
                throw new RuntimeException('Open this page from your Canvas teacher account to enter a sync code.');
            }
            $target = ltiRedeemTeacherAccountLinkCode(
                $pdo,
                $userId,
                trim((string) ($_POST['sync_code'] ?? ''))
            );
            session_regenerate_id(true);
            $_SESSION['user_id'] = (int) $target['id'];
            $_SESSION['name'] = (string) $target['name'];
            $_SESSION['email'] = (string) $target['email'];
            $_SESSION['role'] = (string) $target['role'];
            $_SESSION['account_scope'] = (string) $target['account_scope'];
            unset($_SESSION['csrf_token'], $_SESSION['lti_account_link_code']);
            $_SESSION['lti_account_link_notice'] = 'Your Canvas account and linked course data are now connected to this teacher account.';
            redirect('lti-account-link.php?linked=1');
        } else {
            throw new RuntimeException('Choose a valid account-link action.');
        }
    } catch (Throwable $exception) {
        $error = $exception->getMessage();
    }
}

if (!empty($_GET['linked'])) {
    $notice = (string) ($_SESSION['lti_account_link_notice'] ?? 'Your Canvas account and linked course data are now connected to this teacher account.');
    unset($_SESSION['lti_account_link_notice']);
}

$title = 'Link Canvas Teacher Account';
$pageNoIndex = true;
require_once dirname(__DIR__) . '/includes/header.php';
?>

<h1>Link Canvas Teacher Account</h1>
<div class="card">
    <p>Use a one-time sync code to connect the Canvas-created teacher account to your regular Education teacher account. Linked Canvas courses and related teaching data move to the regular account.</p>

    <?php if ($error !== ''): ?>
        <div class="error" role="alert"><?= e($error) ?></div>
    <?php endif; ?>
    <?php if ($notice !== ''): ?>
        <div class="success" role="status"><?= e($notice) ?></div>
    <?php endif; ?>

    <?php if (!$hasLtiIdentity): ?>
        <h2>Generate a sync code</h2>
        <p>Generate this code while signed into the Education teacher email account you want to keep. Then launch InsQuire from Canvas as the teacher and enter the code there. The code expires in 15 minutes and can only be used once.</p>
        <?php if ($generatedCode !== ''): ?>
            <p><strong>Your one-time sync code:</strong></p>
            <p><code style="font-size:1.4rem;letter-spacing:.12em"><?= e($generatedCode) ?></code></p>
            <p>Copy it now. It will not be shown again after you leave or refresh this page.</p>
        <?php endif; ?>
        <form method="post">
            <input type="hidden" name="csrf_token" value="<?= e(csrfToken()) ?>">
            <input type="hidden" name="action" value="generate">
            <button class="button" type="submit"><?= $generatedCode !== '' ? 'Generate a new code' : 'Generate sync code' ?></button>
        </form>
    <?php else: ?>
        <h2>Enter your sync code</h2>
        <p>You are signed into a Canvas teacher account. Enter the code generated by your regular Education teacher email account. The Canvas-created account will be disabled after its Canvas identity, course ownership, institutional memberships, and related teaching data are moved.</p>
        <form method="post">
            <input type="hidden" name="csrf_token" value="<?= e(csrfToken()) ?>">
            <input type="hidden" name="action" value="redeem">
            <label for="sync-code">One-time sync code</label>
            <input id="sync-code" name="sync_code" type="text" inputmode="text" autocomplete="off" minlength="16" maxlength="16" pattern="[A-Fa-f0-9]{16}" required>
            <button class="button" type="submit">Link accounts and merge data</button>
        </form>
    <?php endif; ?>
</div>

<?php require_once dirname(__DIR__) . '/includes/footer.php'; ?>
